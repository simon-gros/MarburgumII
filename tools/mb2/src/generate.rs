//! `mb2 generate gameplay`: writes the C++ gameplay catalogue header from the gameplay catalogue JSON.
//! The JSON is the source of truth; `mb2 validate gameplay` regenerates the header in memory and fails
//! when the committed file differs (ADR-049).

use std::fmt::Write as _;
use std::path::Path;

use serde_json::Value;

use crate::repo::{self, read_json, Problems};

pub const CATALOGUE: &str = "Data/Gameplay/gameplay.v0.1.json";
pub const HEADER: &str = "Source/MarburgumIIShared/Public/MarburgumGameplayCatalogue.h";

pub fn run(which: &str) -> u8 {
    if which != "gameplay" {
        eprintln!("Unknown generator '{which}'; use gameplay.");
        return 2;
    }
    let root = repo::root();
    let mut problems = Problems::default();
    let catalogue = read_json(&root, CATALOGUE, &mut problems);
    if !problems.is_empty() {
        for problem in &problems.0 {
            eprintln!("{problem}");
        }
        return 1;
    }
    match gameplay_header(&catalogue) {
        Ok(header) => match std::fs::write(root.join(HEADER), header) {
            Ok(()) => {
                println!("Wrote {HEADER}");
                0
            }
            Err(error) => {
                eprintln!("cannot write {HEADER}: {error}");
                1
            }
        },
        Err(error) => {
            eprintln!("{error}");
            1
        }
    }
}

/// The header for a catalogue, or the first structural problem found in it.
pub fn gameplay_header(catalogue: &Value) -> Result<String, String> {
    let mut out = String::new();
    out.push_str(
        "// Generated by `mb2 generate gameplay` from Data/Gameplay/gameplay.v0.1.json. Do not edit by hand:\n\
         // `mb2 validate gameplay` fails when this file differs from the catalogue (ADR-049).\n\
         // Included by MarburgumGameplayContract.h after the definition types.\n\
         #pragma once\n\n\
         namespace MarburgumII::Gameplay\n{\n",
    );

    // Items.
    out.push_str("    inline constexpr FItemDefinition Items[] = {\n");
    for item in array(catalogue, "items")? {
        let kind = match str_of(item, "kind")? {
            "tool" => "Tool",
            "fish" => "Fish",
            "clue" => "Clue",
            other => return Err(format!("item {}: unknown kind {other}", str_of(item, "id")?)),
        };
        writeln!(out, "        {{ {}, {}, EItemKind::{kind} }},", lit(str_of(item, "id")?), lit(en(item, "name")?)).unwrap();
    }
    out.push_str("    };\n\n");

    // Skills.
    out.push_str("    inline constexpr FSkillDefinition Skills[] = {\n");
    for skill in array(&catalogue["skills"], "entries")? {
        writeln!(out, "        {{ {}, {}, {} }},", lit(str_of(skill, "id")?), lit(en(skill, "name")?),
            skill["reversible"].as_bool().unwrap_or(false)).unwrap();
    }
    out.push_str("    };\n\n");

    // Fishing spots.
    let spots = array(&catalogue["fishing"], "spots")?;
    for (index, spot) in spots.iter().enumerate() {
        writeln!(out, "    inline constexpr FFishSpecies FishingSpot{index}Species[] = {{").unwrap();
        for species in array(spot, "species")? {
            writeln!(out, "        {{ {}, {}, {} }},", lit(str_of(species, "item")?), int(species, "weight")?, int(species, "xp")?).unwrap();
        }
        out.push_str("    };\n");
    }
    out.push_str("    inline constexpr FFishingSpotDefinition FishingSpots[] = {\n");
    for (index, spot) in spots.iter().enumerate() {
        writeln!(out, "        {{ {}, {}, FishingSpot{index}Species, UE_ARRAY_COUNT(FishingSpot{index}Species) }},",
            lit(str_of(spot, "id")?), lit(en(spot, "name")?)).unwrap();
    }
    out.push_str("    };\n\n");

    // Interactables placed by the server at runtime (the map places the rest).
    out.push_str("    inline constexpr FInteractableDefinition Interactables[] = {\n");
    for entry in array(catalogue, "interactables")? {
        let placement = match entry["placement"].as_str() {
            Some("map") => "Map",
            Some("original") => "Original",
            Some("angler_relative") => "AnglerRelative",
            Some("unplaced") => "Unplaced",
            Some("pad") => "Pad",
            _ => continue, // test fixtures live in the map commandlet only
        };
        let kind = match str_of(entry, "kind")? {
            "npc" => "Npc",
            "fishing_spot" => "FishingSpot",
            "clue" => "Clue",
            "location" => "Location",
            other => return Err(format!("interactable {}: unknown kind {other}", str_of(entry, "id")?)),
        };
        let position = entry["godot_position_m"].as_array().map(|p| p.iter().filter_map(Value::as_f64).collect::<Vec<_>>())
            .unwrap_or_else(|| vec![0.0, 0.0, 0.0]);
        if position.len() != 3 {
            return Err(format!("interactable {}: godot_position_m needs three numbers", str_of(entry, "id")?));
        }
        let color = |key: &str| -> String {
            entry["colors"][key].as_array().map(|c| c.iter().filter_map(Value::as_f64).map(float).collect::<Vec<_>>().join(", "))
                .filter(|c| !c.is_empty()).unwrap_or_else(|| "0.f, 0.f, 0.f".to_string())
        };
        let dialogue = entry["dialogue"]["en"].as_str().unwrap_or("");
        writeln!(out, "        {{ {}, EInteractableKind::{kind}, {}, {}, {}, {{ {}, {}, {} }}, {}, EPlacement::{placement}, {{ {} }}, {{ {} }} }},",
            lit(str_of(entry, "id")?), lit(en(entry, "display_name")?), lit(verb(entry["verb"].as_str().unwrap_or("inspect"))),
            lit(dialogue), double(position[0]), double(position[1]), double(position[2]), float(entry["range_cm"].as_f64().unwrap_or(300.0)),
            color("primary"), color("secondary")).unwrap();
    }
    out.push_str("    };\n\n");

    // Missions: per-mission arrays first, then the registry.
    let missions = array(catalogue, "missions")?;
    for (m, mission) in missions.iter().enumerate() {
        let prefix = format!("Mission{m}");
        string_array(&mut out, &format!("{prefix}Requires"), array(mission, "requires_completed")?.iter().filter_map(Value::as_str));
        quantities(&mut out, &format!("{prefix}StartItems"), array(mission, "start_items")?)?;
        let stages = array(mission, "stages")?;
        for (s, stage) in stages.iter().enumerate() {
            let sp = format!("{prefix}Stage{s}");
            string_array(&mut out, &format!("{sp}Items"), array(&stage["objective"], "items")?.iter().filter_map(Value::as_str));
            quantities(&mut out, &format!("{sp}Required"), array(stage, "required_items")?)?;
            quantities(&mut out, &format!("{sp}Grants"), array(stage, "grant_items")?)?;
            flags(&mut out, &format!("{sp}Flags"), &stage["set_flags"]);
            let choices = array(stage, "choices")?;
            for (c, choice) in choices.iter().enumerate() {
                let cp = format!("{sp}Choice{c}");
                skill_xp(&mut out, &format!("{cp}Xp"), &choice["skill_xp"])?;
                flags(&mut out, &format!("{cp}Flags"), &choice["set_flags"]);
            }
            if !choices.is_empty() {
                writeln!(out, "    inline constexpr FMissionChoiceDefinition {sp}Choices[] = {{").unwrap();
                for (c, choice) in choices.iter().enumerate() {
                    let cp = format!("{sp}Choice{c}");
                    writeln!(out, "        {{ {}, {}, {}, {}, {}, {}, {} }},", lit(str_of(choice, "id")?), lit(en(choice, "label")?),
                        int(choice, "money_delta")?, span(&format!("{cp}Xp"), !object_empty(&choice["skill_xp"])),
                        lit(choice["outcome"].as_str().unwrap_or(str_of(choice, "id")?)), lit(choice["completion_text"]["en"].as_str().unwrap_or("")),
                        span(&format!("{cp}Flags"), !object_empty(&choice["set_flags"]))).unwrap();
                }
                out.push_str("    };\n");
            }
        }
        writeln!(out, "    inline constexpr FMissionStageDefinition {prefix}Stages[] = {{").unwrap();
        for (s, stage) in stages.iter().enumerate() {
            let sp = format!("{prefix}Stage{s}");
            let objective = &stage["objective"];
            let kind = match str_of(objective, "type")? {
                "interaction" => "Interaction",
                "inventory_any" => "InventoryAny",
                "choice" => "Choice",
                other => return Err(format!("mission {}: stage {}: unknown objective {other}", str_of(mission, "id")?, str_of(stage, "id")?)),
            };
            let items = array(objective, "items")?;
            writeln!(out, "        {{ {}, {}, {}, {}, EObjectiveType::{kind}, {}, {}, {}, {}, {}, {}, {}, {}, {} }},",
                lit(str_of(stage, "id")?), lit(en(stage, "objective_text")?), lit(str_of(stage, "complete_target")?), lit(en(stage, "action")?),
                span(&format!("{sp}Items"), !items.is_empty()), objective["quantity"].as_i64().unwrap_or(1),
                objective["consume"].as_bool().unwrap_or(false),
                span(&format!("{sp}Required"), !array(stage, "required_items")?.is_empty()),
                span(&format!("{sp}Grants"), !array(stage, "grant_items")?.is_empty()),
                span(&format!("{sp}Flags"), !object_empty(&stage["set_flags"])),
                span(&format!("{sp}Choices"), !array(stage, "choices")?.is_empty()),
                stage["final"].as_bool().unwrap_or(false), lit(stage["completion_text"]["en"].as_str().unwrap_or(""))).unwrap();
        }
        out.push_str("    };\n\n");
    }
    out.push_str("    inline constexpr FMissionDefinition Missions[] = {\n");
    for (m, mission) in missions.iter().enumerate() {
        let prefix = format!("Mission{m}");
        let journal = &mission["journal_entry"];
        writeln!(out, "        {{ {}, {}, {}, {}, {}, {}, {}, {}, {}Stages, UE_ARRAY_COUNT({}Stages), {}, {}, {}, {} }},",
            lit(str_of(mission, "id")?), lit(en(mission, "name")?), lit(str_of(mission, "category")?), lit(str_of(mission, "offer_target")?),
            lit(en(mission, "summary")?), lit(mission["story_family"].as_str().unwrap_or("")),
            span(&format!("{prefix}Requires"), !array(mission, "requires_completed")?.is_empty()),
            span(&format!("{prefix}StartItems"), !array(mission, "start_items")?.is_empty()),
            prefix, prefix, mission["reward_money"].as_i64().unwrap_or(0),
            lit(journal["id"].as_str().unwrap_or("")), lit(journal["title"]["en"].as_str().unwrap_or("")),
            lit(journal["text"]["en"].as_str().unwrap_or(""))).unwrap();
    }
    out.push_str("    };\n}\n");
    Ok(out)
}

fn array<'a>(value: &'a Value, key: &str) -> Result<&'a [Value], String> {
    match &value[key] {
        Value::Null => Ok(&[]),
        Value::Array(items) => Ok(items.as_slice()),
        _ => Err(format!("`{key}` is not an array")),
    }
}

fn str_of<'a>(value: &'a Value, key: &str) -> Result<&'a str, String> {
    value[key].as_str().ok_or_else(|| format!("missing string `{key}` in {}", short(value)))
}

fn en<'a>(value: &'a Value, key: &str) -> Result<&'a str, String> {
    value[key]["en"].as_str().ok_or_else(|| format!("missing `{key}.en` in {}", short(value)))
}

fn int(value: &Value, key: &str) -> Result<i64, String> {
    value[key].as_i64().ok_or_else(|| format!("missing integer `{key}` in {}", short(value)))
}

fn short(value: &Value) -> String {
    value["id"].as_str().map(str::to_string).unwrap_or_else(|| value.to_string().chars().take(60).collect())
}

fn object_empty(value: &Value) -> bool {
    value.as_object().map_or(true, |o| o.is_empty())
}

fn verb(raw: &str) -> &'static str {
    match raw {
        "talk" => "Talk",
        "fish" => "Fish",
        "take" => "Take",
        _ => "Inspect",
    }
}

/// `Name, UE_ARRAY_COUNT(Name)` or `nullptr, 0`.
fn span(name: &str, present: bool) -> String {
    if present {
        format!("{name}, UE_ARRAY_COUNT({name})")
    } else {
        "nullptr, 0".to_string()
    }
}

fn string_array<'a>(out: &mut String, name: &str, values: impl Iterator<Item = &'a str>) {
    let values: Vec<String> = values.map(lit).collect();
    if !values.is_empty() {
        writeln!(out, "    inline constexpr const TCHAR* {name}[] = {{ {} }};", values.join(", ")).unwrap();
    }
}

fn quantities(out: &mut String, name: &str, values: &[Value]) -> Result<(), String> {
    if values.is_empty() {
        return Ok(());
    }
    let mut parts = Vec::new();
    for value in values {
        parts.push(format!("{{ {}, {} }}", lit(str_of(value, "id")?), int(value, "quantity")?));
    }
    writeln!(out, "    inline constexpr FItemQuantity {name}[] = {{ {} }};", parts.join(", ")).unwrap();
    Ok(())
}

fn flags(out: &mut String, name: &str, value: &Value) {
    if let Some(object) = value.as_object().filter(|o| !o.is_empty()) {
        let parts: Vec<String> = object.iter().map(|(k, v)| format!("{{ {}, {} }}", lit(k), v.as_bool().unwrap_or(false))).collect();
        writeln!(out, "    inline constexpr FMissionFlag {name}[] = {{ {} }};", parts.join(", ")).unwrap();
    }
}

fn skill_xp(out: &mut String, name: &str, value: &Value) -> Result<(), String> {
    if let Some(object) = value.as_object().filter(|o| !o.is_empty()) {
        let mut parts = Vec::new();
        for (skill, xp) in object {
            parts.push(format!("{{ {}, {} }}", lit(skill), xp.as_i64().ok_or_else(|| format!("{name}: XP for {skill} is not an integer"))?));
        }
        writeln!(out, "    inline constexpr FSkillXp {name}[] = {{ {} }};", parts.join(", ")).unwrap();
    }
    Ok(())
}

/// A TEXT("...") literal; non-ASCII characters become universal character names so the source stays ASCII.
fn lit(text: &str) -> String {
    let mut out = String::from("TEXT(\"");
    for c in text.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            ' '..='~' => out.push(c),
            c if (c as u32) <= 0xFFFF => write!(out, "\\u{:04X}", c as u32).unwrap(),
            c => write!(out, "\\U{:08X}", c as u32).unwrap(),
        }
    }
    out.push_str("\")");
    out
}

fn double(value: f64) -> String {
    let text = format!("{value}");
    if text.contains('.') || text.contains('e') { text } else { format!("{text}.0") }
}

fn float(value: f64) -> String {
    format!("{}f", double(value))
}

/// Used by the validator.
pub fn check(root: &Path, catalogue: &Value, problems: &mut Problems) {
    match gameplay_header(catalogue) {
        Ok(expected) => {
            let actual = std::fs::read_to_string(root.join(HEADER)).unwrap_or_default();
            problems.expect(actual == expected, format!("{HEADER} is stale: run `scripts/mb2.sh generate gameplay`"));
        }
        Err(error) => problems.0.push(format!("gameplay catalogue: {error}")),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn literals_escape_quotes_and_non_ascii() {
        assert_eq!(lit("a\"b"), "TEXT(\"a\\\"b\")");
        assert_eq!(lit("Šolar — R-90"), "TEXT(\"\\u0160olar \\u2014 R-90\")");
    }

    #[test]
    fn numbers_always_carry_a_decimal_point() {
        assert_eq!(double(-127.0), "-127.0");
        assert_eq!(double(2.1), "2.1");
        assert_eq!(float(400.0), "400.0f");
    }
}
